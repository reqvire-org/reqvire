import { useState } from "preact/hooks";
import { RouteFrame } from "../shell/RouteFrame";
import { CoverageDrilldown, type CoverageDrilldownItem, type CoverageDrilldownTarget } from "./CoverageDrilldown";
import {
  CoverageBarFrame, CoverageBarList, CoverageBreakdownFrame, CoverageDashboard,
  CoverageEmptyNote, CoverageEmptyState, CoverageGapGrid, CoverageGapListFrame,
  CoverageGapRowButton, CoverageGapRows, CoverageGrid, CoverageHeader,
  CoverageKpiCard, CoverageKpiGrid, CoverageLegendRow, CoverageMoreButton,
  CoveragePanel, CoverageSourceRow, ReportRouteLayout,
} from "./ReportPatterns";
import { SegmentedMeter } from "../../components/data/TokenVisual";
import type { DesignSystemColorToken } from "../../palette";

export const COVERAGE_ISSUES = [
  { id: "unverified-requirements", label: "Unverified requirements", field: "unverified_leaf_requirements", emptyLabel: "All leaf requirements have verification." },
  { id: "unimplemented-requirements", label: "Unimplemented requirements", field: "uncovered_requirements", emptyLabel: "All requirements in scope are implementation-covered." },
  { id: "unsatisfied-verifications", label: "Unsatisfied verifications", field: "unsatisfied_test_verifications", emptyLabel: "All test verifications have evidence." },
  { id: "orphaned-verifications", label: "Orphaned verifications", field: "orphaned_verifications", emptyLabel: "Every verification links to a requirement." },
] as const;
export const COVERAGE_SOURCE_LABELS: Record<string, string> = {
  direct_satisfied: "Direct evidence",
  requirement_rollup: "Requirement rollup",
  contract_consumer_rollup: "Contract consumer rollup",
  combined_rollup: "Combined rollup",
  uncovered: "Uncovered",
};

export interface CoverageReportSummary {
  covered_requirements?: number;
  covered_terminal_requirements?: number;
  implementation_coverage_percentage?: number;
  leaf_requirements_coverage_percentage?: number;
  orphaned_verifications?: number;
  orphaned_verifications_percentage?: number;
  satisfied_test_verifications?: number;
  test_verifications_satisfaction_percentage?: number;
  total_leaf_requirements?: number;
  total_requirements_in_scope?: number;
  total_terminal_requirements?: number;
  total_test_verifications?: number;
  total_verifications?: number;
  verified_leaf_requirements?: number;
  verification_types?: Record<string, number>;
  coverage_sources?: Record<string, number>;
}
export interface CoverageReportProjection {
  summary?: CoverageReportSummary;
  scope?: { capability_name?: string } | null;
  [section: string]: unknown;
}
interface CoverageElement { element_type: string; type_family: string; }
interface CoverageRequirementDetails { identifier: string; name: string; verified_by?: string[]; }
type CoverageFileItem<T> = T & { file: string };
export interface CoverageReportScreenProps {
  coverage: CoverageReportProjection;
  capabilityRows: CoverageDrilldownItem[];
  scopeId: string | null;
  contextKey: string;
  notice?: string | null;
  elementById: (id: string) => CoverageElement | undefined;
  onOpenElement?: (id: string) => void;
  onInspect: (target: CoverageDrilldownTarget) => void;
}

/** Published report presentation; data projection and navigation stay with the consumer. */
export function CoverageReportScreen({ coverage, capabilityRows, scopeId, contextKey,
  notice, elementById, onOpenElement, onInspect }: CoverageReportScreenProps) {
  const summary = coverage.summary ?? {};
  const scoped = Boolean(coverage.scope);
  const hasCoverageData = Object.keys(summary).length > 0;

  return <RouteFrame viewId="coverage">
    <ReportRouteLayout><CoverageDashboard>
      <CoverageHeader eyebrow="Coverage" title={coverage.scope?.capability_name ?? "Whole Model"} />
      {notice && <CoverageEmptyNote>{notice}</CoverageEmptyNote>}
      {!hasCoverageData ? <CoverageEmptyState title="No coverage report in this Explorer seed">
        Serve or open a Project Store generated by Reqvire to inspect requirement and verification coverage.
      </CoverageEmptyState> : <>
        {scoped && summary.total_requirements_in_scope === 0
          && <CoverageEmptyNote>No requirements in this capability scope.</CoverageEmptyNote>}
        <CoverageKpiGrid>
          <CoverageKpi label="Leaf verification" value={summary.leaf_requirements_coverage_percentage}
            detail={`${formatNumber(summary.verified_leaf_requirements)} / ${formatNumber(summary.total_leaf_requirements)} verified`} token="--color-role-requirement" />
          <CoverageKpi label="Implementation" value={summary.implementation_coverage_percentage}
            detail={summary.total_terminal_requirements === undefined
              ? `${formatNumber(summary.covered_requirements)} / ${formatNumber(summary.total_requirements_in_scope)} covered`
              : `${formatNumber(summary.covered_terminal_requirements)} / ${formatNumber(summary.total_terminal_requirements)} terminal requirements covered`} token="--color-role-resource" />
          <CoverageKpi label="Test evidence" value={summary.test_verifications_satisfaction_percentage}
            detail={`${formatNumber(summary.satisfied_test_verifications)} / ${formatNumber(summary.total_test_verifications)} satisfied`} token="--color-role-verification" />
          {!scoped && <CoverageKpi label="Orphaned verifications" value={summary.orphaned_verifications_percentage}
            detail={`${formatNumber(summary.orphaned_verifications)} / ${formatNumber(summary.total_verifications)} orphaned`} token="--color-role-contract" inverted />}
        </CoverageKpiGrid>
        <CoverageGrid compact>
          <CoveragePanel title="Verification types"><CoverageBreakdown values={summary.verification_types ?? {}} rows={[
            ["test", "Test", "test-verification"], ["formal_proof", "Formal proof", "formal-proof-verification"],
            ["analysis", "Analysis", "analysis-verification"], ["inspection", "Inspection", "inspection-verification"],
            ["demonstration", "Demonstration", "demonstration-verification"],
          ]} /></CoveragePanel>
          <CoveragePanel title="Implementation sources"><CoverageSourceBars values={summary.coverage_sources ?? {}} /></CoveragePanel>
        </CoverageGrid>
        <CoveragePanel id={coverageSectionDomId("capability-coverage")}
          title={capabilityRows.length ? undefined : "Capability coverage"} span="wide">
          {capabilityRows.length ? <CoverageDrilldown key={scopeId ?? "whole"} items={capabilityRows}
            onInspect={onInspect} /> : <CoverageEmptyNote>No capability coverage rows were reported.</CoverageEmptyNote>}
        </CoveragePanel>
        <CoverageGapGrid key={contextKey}>
          {COVERAGE_ISSUES.filter(item => !scoped || item.id !== "orphaned-verifications").map(item => <CoverageGapList
            key={item.id} id={coverageSectionDomId(item.id)} title={item.label}
            items={coverageFileItems<CoverageRequirementDetails>(coverage[item.field])} emptyLabel={item.emptyLabel}
            defaultType={item.id.includes("verifications") ? "test-verification" : "requirement"}
            elementById={elementById} onOpenElement={onOpenElement} />)}
        </CoverageGapGrid>
        {scoped && <CoverageEmptyNote>Orphaned verifications are whole-model diagnostics. Select Whole Model in the capability tree to see them.</CoverageEmptyNote>}
      </>}
    </CoverageDashboard></ReportRouteLayout>
  </RouteFrame>;
}

function CoverageKpi({
  label,
  value,
  detail,
  token,
  inverted = false,
}: {
  label: string;
  value?: number;
  detail: string;
  token: DesignSystemColorToken;
  inverted?: boolean;
}) {
  const percent = clampPercent(value ?? 0);
  const shown = typeof value === "number" ? formatPercent(value) : "—";
  const ringPercent = inverted ? 100 - percent : percent;
  return (
    <CoverageKpiCard
      label={label}
      detail={detail}
      shown={shown}
      ringPercent={ringPercent}
      token={token}
    />
  );
}

function CoverageBreakdown({
  values,
  rows,
}: {
  values: Record<string, number>;
  rows: [string, string, string][];
}) {
  const tokens: readonly DesignSystemColorToken[] = ["--color-role-verification-type-test", "--color-role-verification-type-formal-proof",
    "--color-role-verification-type-analysis", "--color-role-verification-type-inspection", "--color-role-verification-type-demonstration"];
  return (
    <CoverageBreakdownFrame bar={<SegmentedMeter aria-hidden="true" segments={rows.map(([key, label], index) => ({
      label, value: values[key] ?? 0, colorToken: tokens[index],
    }))} />}>
      {rows.map(([key, label, type], index) => (
        <CoverageLegendRow key={key} label={label} value={formatNumber(values[key] ?? 0)} type={type} colorToken={tokens[index]} />
      ))}
    </CoverageBreakdownFrame>
  );
}

function CoverageSourceBars({ values }: { values: Record<string, number> }) {
  const rows: [string, string, DesignSystemColorToken][] = [
    ["direct_satisfied", COVERAGE_SOURCE_LABELS.direct_satisfied, "--color-role-resource"],
    ["requirement_rollup", COVERAGE_SOURCE_LABELS.requirement_rollup, "--color-role-capability"],
    ["contract_consumer_rollup", COVERAGE_SOURCE_LABELS.contract_consumer_rollup, "--color-role-ontology"],
    ["combined_rollup", COVERAGE_SOURCE_LABELS.combined_rollup, "--color-role-requirement"],
  ];
  for (const key of ["contract_satisfied_via_contract_bindings", "contract_satisfied_via_child"]) {
    if (key in values) rows.push([key, COVERAGE_SOURCE_LABELS[key], "--color-role-ontology"]);
  }
  const max = Math.max(1, ...rows.map(([key]) => values[key] ?? 0));
  return (
    <CoverageBarList>
      {rows.map(([key, label, token]) => {
        const value = values[key] ?? 0;
        return (
          <CoverageSourceRow key={key} label={label} value={formatNumber(value)}>
            <CoverageBar value={(value / max) * 100} token={token} />
          </CoverageSourceRow>
        );
      })}
    </CoverageBarList>
  );
}

function CoverageGapList<T extends { identifier: string; name: string; file: string }>({
  id,
  title,
  items,
  emptyLabel,
  defaultType,
  elementById,
  onOpenElement,
}: {
  id?: string;
  title: string;
  items: T[];
  emptyLabel: string;
  defaultType: string;
  elementById: (id: string) => CoverageElement | undefined;
  onOpenElement?: (id: string) => void;
}) {
  const [expanded, setExpanded] = useState(false);
  const visibleLimit = 8;
  const visible = expanded ? items : items.slice(0, visibleLimit);
  const hiddenCount = Math.max(0, items.length - visible.length);
  return (
    <CoverageGapListFrame id={id} title={title} count={formatNumber(items.length)}>
      {items.length === 0 ? (
        <CoverageEmptyNote>{emptyLabel}</CoverageEmptyNote>
      ) : (
        <CoverageGapRows>
          {visible.map((item) => {
            const element = elementById(item.identifier);
            const type = element?.element_type ?? defaultType;
            const family = element?.type_family ?? defaultType;
            return (
              <CoverageGapRowButton
                key={`${item.file}:${item.identifier}`}
                type={type}
                family={family}
                title={item.name || displayIdentifier(item.identifier)}
                file={item.file}
                typeLabel={humanizeType(type)}
                onClick={() => onOpenElement?.(item.identifier)}
              />
            );
          })}
          {items.length > visibleLimit ? (
            <CoverageMoreButton
              aria-expanded={expanded}
              onClick={() => setExpanded((current) => !current)}
            >
              {expanded ? "Show fewer" : `+ ${formatNumber(hiddenCount)} more`}
            </CoverageMoreButton>
          ) : null}
        </CoverageGapRows>
      )}
    </CoverageGapListFrame>
  );
}

function coverageSectionDomId(section: string) {
  return `coverage-section-${section}`;
}

function CoverageBar({ value, token }: { value: number; token: DesignSystemColorToken }) {
  return <CoverageBarFrame value={clampPercent(value)} token={token} />;
}

function coverageFileItems<T>(section: unknown): Array<CoverageFileItem<T>> {
  if (!isRecord(section) || !isRecord(section.files)) return [];
  const rows: Array<CoverageFileItem<T>> = [];
  for (const [file, value] of Object.entries(section.files)) {
    if (!Array.isArray(value)) continue;
    for (const item of value) {
      if (isRecord(item)) {
        rows.push({ file, ...(item as T) });
      }
    }
  }
  return rows.sort((left, right) => {
    const leftName = String((left as { name?: unknown }).name ?? "");
    const rightName = String((right as { name?: unknown }).name ?? "");
    return left.file.localeCompare(right.file) || leftName.localeCompare(rightName);
  });
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function clampPercent(value: number) {
  if (!Number.isFinite(value)) return 0;
  return Math.max(0, Math.min(100, value));
}

function formatPercent(value: number | undefined) {
  if (typeof value !== "number" || !Number.isFinite(value)) return "—";
  return `${roundOne(value)}%`;
}

function roundOne(value: number) {
  return Number.isInteger(value) ? value.toString() : value.toFixed(1).replace(/\.0$/, "");
}

function formatNumber(value: number | undefined) {
  return typeof value === "number" && Number.isFinite(value) ? value.toLocaleString() : "0";
}

function displayIdentifier(identifier: string) {
  const fragment = identifier.split("#").pop();
  return fragment ? fragment.replace(/-/g, " ") : identifier;
}

function humanizeType(value: string) {
  return value.replace(/-/g, " ");
}
